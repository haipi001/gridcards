// Binds a real card scan to every checklist record that the 1/1 archive has
// photographed, so the home grid shows actual cards instead of generated art.
//
//   node scripts/gen-catalog-images.mjs
//
// Output: src/data/catalogImages.ts — "{section}#{cardNumber}" -> /img/archive/*.jpg
//
// Keyed by section + card number rather than by driver name because the same
// driver appears in several sections (base, autograph variations, image
// variations …) and each of those is a physically different card.

import fs from "node:fs";
import path from "node:path";
import { createImagePicker, ROOT } from "./lib/cardImages.mjs";

const source = JSON.parse(
  fs.readFileSync(path.join(ROOT, "src", "data", "catalog.json"), "utf8"),
);

// Same picker the market generator uses, so a driver either has a photo in both
// places or in neither.
const picker = createImagePicker();
const images = {};
let matched = 0;
let total = 0;

for (const section of source.sections) {
  for (const card of section.cards) {
    total += 1;
    const image = picker.next(card.name);
    if (!image) continue;
    images[`${section.slug}#${card.cardNumber}`] = image;
    matched += 1;
  }
}

const body = Object.entries(images)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");

fs.writeFileSync(
  path.join(ROOT, "src", "data", "catalogImages.ts"),
  `// GENERATED by scripts/gen-catalog-images.mjs — do not edit by hand.
//
// Real 1/1 scan for a checklist record, keyed "section#cardNumber". Records the
// archive has never photographed are simply absent; the UI falls back to
// generated livery art for those.

export const CATALOG_IMAGES: Record<string, string> = {
${body}
};

export function catalogImage(
  sectionSlug: string,
  cardNumber: string,
): string | null {
  return CATALOG_IMAGES[\`\${sectionSlug}#\${cardNumber}\`] ?? null;
}
`,
  "utf8",
);

console.log(`checklist images: ${matched}/${total} records matched a real scan`);
