// Binds a real card scan to every checklist record, using the same allocation
// the market uses — so the two views can never show different photos for one
// card, and no photograph is ever on two cards at once.
//
//   node scripts/gen-catalog-images.mjs
//
// Output: src/data/catalogImages.ts — "{section}#{cardNumber}" -> scan
//
// A record shows its Base edition's photo: the checklist row *is* the base
// card, so handing it the 1/1's scan would label the wrong parallel.

import fs from "node:fs";
import path from "node:path";
import { ROOT } from "./lib/cardImages.mjs";
import { buildPhotoPlan } from "./lib/cardPhotoPlan.mjs";

const source = JSON.parse(
  fs.readFileSync(path.join(ROOT, "src", "data", "catalog.json"), "utf8"),
);

const { records } = buildPhotoPlan(["src", "data", "catalog.json"]);
const images = {};
let matched = 0;
let exact = 0;
let total = 0;

for (const section of source.sections) {
  for (const card of section.cards) {
    total += 1;
    const scan = records.get(`${section.slug}#${card.cardNumber}`);
    if (!scan) continue;
    images[`${section.slug}#${card.cardNumber}`] = {
      src: scan.src,
      setShort: scan.setShort,
      year: scan.year,
      exact: scan.exact,
    };
    matched += 1;
    if (scan.exact) exact += 1;
  }
}

const body = Object.entries(images)
  .map(
    ([k, v]) =>
      `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`,
  )
  .join("\n");

fs.writeFileSync(
  path.join(ROOT, "src", "data", "catalogImages.ts"),
  `// GENERATED by scripts/gen-catalog-images.mjs — do not edit by hand.
//
// Real card scan for a checklist record, keyed "section#cardNumber". Records the
// archive has never photographed (or whose photos are all spoken for) are simply
// absent; the UI falls back to generated livery art for those.
//
// \`exact\` is true only for a 2020 Topps Chrome scan. Everything else is the
// same driver photographed in another set — \`setShort\`/\`year\` name which one,
// and the UI must label it rather than pass it off as this card.

export type CatalogImage = {
  src: string;
  /** "Chrome" / "Dynasty" / "Eccellenza" … */
  setShort: string;
  year: number | null;
  /** True only for a 2020 Topps Chrome scan. */
  exact: boolean;
};

export const CATALOG_IMAGES: Record<string, CatalogImage> = {
${body}
};

export function catalogImage(
  sectionSlug: string,
  cardNumber: string,
): CatalogImage | null {
  return CATALOG_IMAGES[\`\${sectionSlug}#\${cardNumber}\`] ?? null;
}
`,
  "utf8",
);

console.log(
  `checklist images: ${matched}/${total} records matched a real scan (${exact} from 2020 Chrome)`,
);
